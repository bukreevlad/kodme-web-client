// Импортируем bun test
import { describe, expect, test } from "bun:test";

// Импортируем utils
import { calculateAspectRatio } from "../js/utils/helpers/calculate_aspect_ratio.js";

/**
 * ***************************************************************************
 * Смоук-тесты миграции: проверяют, что чистые утилиты клиента работают
 * и что сборка тестов запускается (базовая защита при миграции JS → TS).
 * ***************************************************************************
 */
describe("смоук-тесты клиента", () => {

    /**
     * ***************************************************************************
     * Вычисление aspect ratio для медиа (без DOM).
     * ***************************************************************************
     */
    test("calculateAspectRatio считает НОД-отношение сторон", () => {
        const result = calculateAspectRatio(1920, 1080);
        expect(result?.ratio).toBe("16:9");
        expect(result?.decimal).toBeCloseTo(16 / 9);
    });

    /**
     * ***************************************************************************
     * Пустые размеры дают null, как в легаси.
     * ***************************************************************************
     */
    test("calculateAspectRatio возвращает null на пустых размерах", () => {
        expect(calculateAspectRatio(0, 100)).toBeNull();
        expect(calculateAspectRatio(100, 0)).toBeNull();
    });

});
