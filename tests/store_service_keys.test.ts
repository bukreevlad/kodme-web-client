// Импортируем bun test
import { describe, expect, mock, test } from "bun:test";

// Импортируем utils
import { Store } from "../js/utils/store.js";

// Импортируем типы
import type { StoreItem } from "../js/utils/store.js";

/**
 * ***************************************************************************
 * Тесты работы Store со служебными ключами записей: update не переносит
 * DOM-состояние и хуки компонентов между записями (запись может быть
 * общей для нескольких сторов), а прямые записи на объект переживают update.
 * ***************************************************************************
 */
describe("служебные ключи Store", () => {

    /**
     * ***************************************************************************
     * Обновление не смешивает служебное состояние чужой записи с целевой.
     * ***************************************************************************
     */
    test("update не переносит служебные ключи между записями", () => {
        const store = new Store();
        store.add({ id: "a", title: "до" });

        store.update("a", {
            title: "после",
            __domElements__: ["чужая копия"],
            __update__: mock(() => {})
        });

        const item = store.get("a");
        expect(item?.title).toBe("после");
        expect("__domElements__" in (item ?? {})).toBe(false);
        expect("__update__" in (item ?? {})).toBe(false);
    });

    /**
     * ***************************************************************************
     * Хук, записанный компонентом на объект напрямую, переживает update.
     * ***************************************************************************
     */
    test("прямая запись хука на объект переживает update", () => {
        const store = new Store();
        const record: StoreItem = { id: "a", title: "до" };
        const hook = mock(() => {});
        store.add(record);

        // Компоненты пишут хуки на объект записи напрямую, минуя update
        record.__update__ = hook;
        store.update("a", { title: "после" });

        expect(store.get("a")?.__update__).toBe(hook);
    });

});
