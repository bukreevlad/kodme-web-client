/**
 * ***************************************************************************
 * Преобразует строку (UUID) в простое числовое хеш-значение.
 * Использует алгоритм djb2.
 * @param str - Входная строка (UUID).
 * @returns Неотрицательное целое число.
 * ***************************************************************************
 */
export function hashString(str: string): number {

    let hash = 0;
    for (let i = 0; i < str.length; i++) {
        const char = str.charCodeAt(i);
        hash = ((hash * 31) + char); // Простой и быстрый хеш
    }
    return Math.abs(hash); // Гарантируем неотрицательное число

}
