/**
 * ***************************************************************************
 * Склоняет числительное: возвращает форму слова по правилам русского языка.
 * @param integer - Число.
 * @param words - Формы слова: [для 1, для 2–4, для 5–20] (и так циклически).
 * @returns Подобранная форма слова (undefined, если формы не переданы).
 * ***************************************************************************
 */
export function getDeclension(integer: number, words: readonly string[]): string | undefined {

    return (words[(integer = (integer = integer % 100) > 19 ? (integer % 10) : integer) == 1 ? 0 : ((integer > 1 && integer <= 4) ? 1 : 2)]);

}
