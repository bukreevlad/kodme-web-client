/**
 * ***************************************************************************
 * Раскодирует HTML-сущности (&amp;, &lt;, &gt;, &quot;, &#39;) в исходные символы.
 * @param text - Текст.
 * @returns Раскодированная строка.
 * ***************************************************************************
 */
export function unescapeHtml(text: string): string {

    // Выполняем действия
    text = text.trim()
        .replace(/&amp;/g, "&")
        .replace(/&lt;/g, "<")
        .replace(/&gt;/g, ">")
        .replace(/&quot;/g, '"')
        .replace(/&#39;/g, "'");

    // Возвращяем строку
    return text;

}
