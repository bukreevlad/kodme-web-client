/**
 * ***************************************************************************
 * Менеджер состояния приложения
 * ***************************************************************************
 */
export class AppStatus {

    /** Элемент, где отображается статус. */
    element: HTMLElement | null;
    /** Название организации (текст по умолчанию). */
    appName: string;

    /**
     * ***************************************************************************
     * @param {HTMLElement | null} element - Элемент, где отображается статус.
     * @param {String} appName - Название организации.
     * ***************************************************************************
     */
    constructor(element: HTMLElement | null, appName: string) {
        this.element = element;
        this.appName = appName;
    }

    /**
     * ***************************************************************************
     * Установить статус.
     * @param {Object} [data] - Данные статуса.
     * @param {String} [data.text] - Текст.
     * ***************************************************************************
     */
    setStatus(data: { text?: string }): void {

        // Проверяем элемент
        if (!this.element) return;

        // Устанавливаем текст
        // NOTE(MIGRATION): реальный баг легаси — при text: undefined в разметку
        // попадала строка "undefined" (приведение к строке в DOM); нормализуем в null → ""
        this.element.textContent = data.text ?? null;

    }

    /**
     * ***************************************************************************
     * Очистить статус
     * ***************************************************************************
     */
    clearStatus(): void {

        // Проверяем элемент (до инициализации шаблона очищать нечего)
        if (!this.element) return;

        this.element.textContent = this.appName;
    }

}
