/**
 * ***************************************************************************
 * LAYER_STACK - Реестр открытых оверлеев (форм, модалок, контекстных меню).
 * ***************************************************************************
 *
 * Зачем нужен реестр:
 * одновременно открыто несколько слоёв (home → форма → диалог → меню),
 * а клавишу Escape слушает каждый из них прямо на document.
 * Без реестра одно нажатие Escape закрывало бы сразу несколько слоёв.
 * Реестр позволяет отвечать только верхнему слою — так же, как работает
 * нативный <dialog>.
 *
 * Порядок в стеке совпадает с порядком открытия, а значит и с порядком
 * в DOM: у всех форм одинаковый z-index, поэтому выше стоит тот,
 * кто смонтирован позже.
 */

/**
 * Слой реестра: форма / диалог / контекстное меню с контейнером в DOM.
 * Интерфейс намеренно минимален — реестру важны только контейнер
 * (для проверки «смонтирован ли слой») и ссылочная идентичность.
 */
export interface LayerInstance {
    /** Контейнер слоя в DOM (wrap). */
    wrap?: Element | null;
}

export class LayerStack {

    /** Стек открытых слоёв, последний элемент — самый верхний. */
    static _layers: LayerInstance[] = [];

    /**
     * ***************************************************************************
     * Регистрирует слой и делает его самым верхним.
     * @param {LayerInstance} instance - Экземпляр Overlay / ContextMenu.
     * ***************************************************************************
     */
    static push(instance: LayerInstance): void {
        if (!instance) return;

        // Повторная регистрация того же слоя не должна плодить дубликаты
        this.remove(instance);

        this._layers.push(instance);
    }

    /**
     * ***************************************************************************
     * Убирает слой из стека.
     * @param {LayerInstance} instance - Экземпляр Overlay / ContextMenu.
     * ***************************************************************************
     */
    static remove(instance: LayerInstance): void {
        if (!instance) return;

        this._layers = this._layers.filter(layer => layer !== instance);
    }

    /**
     * ***************************************************************************
     * Поднимает уже открытый слой наверх (например при переключении таба формы).
     * Если слоя в стеке нет — ничего не делает: он не смонтирован.
     * @param {LayerInstance} instance - Экземпляр Overlay / ContextMenu.
     * ***************************************************************************
     */
    static raise(instance: LayerInstance): void {
        if (!instance || !this._layers.includes(instance)) return;

        this.remove(instance);
        this._layers.push(instance);
    }

    /**
     * ***************************************************************************
     * Убирает из стека слои, которые уже не смонтированы в DOM.
     * Нужен, чтобы «мёртвый» слой (например, убитый вместе с родителем)
     * не перехватывал Escape и не блокировал всё остальное.
     * @private
     * ***************************************************************************
     */
    static _prune(): void {
        this._layers = this._layers.filter(layer => layer?.wrap?.isConnected === true);
    }

    /**
     * ***************************************************************************
     * Является ли слой верхним в стеке.
     * Только верхний слой имеет право реагировать на Escape.
     * @param {LayerInstance} instance - Экземпляр Overlay / ContextMenu.
     * @returns {boolean} true, если слой самый верхний.
     * ***************************************************************************
     */
    static isTop(instance: LayerInstance): boolean {
        this._prune();

        const top = this._layers[this._layers.length - 1];

        return !!top && top === instance;
    }

    /**
     * ***************************************************************************
     * Полный сброс реестра (например при перезагрузке приложения).
     * ***************************************************************************
     */
    static clear(): void {
        this._layers = [];
    }

}
