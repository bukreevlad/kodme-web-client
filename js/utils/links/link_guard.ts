/**
 * ***************************************************************************
 * LinkGuard - единая логика клика по ссылке: свои ссылки открываем сразу,
 * чужие — через подтверждение.
 *
 * Зачем нужен модуль: логика была продублирована в двух местах
 * (messages/urlify.js, channel-profile/url.js), и в
 * копиях она разошлась. В channel-profile origin сравнивался по
 * `protocol//hostname` — без порта, поэтому на :3000/:8080 даже свои ссылки
 * считались внешними и на них всплывал диалог.
 *
 * Сравнение идёт по полному origin: `hostname` без порта, во-первых, ломал
 * нестандартные порты, во-вторых, пропускал внешний домен, отличающийся от
 * нашего только портом.
 *
 * Диалог подтверждения намеренно НЕ импортируется: utils не должен зависеть
 * от форм. Вызывающий передаёт `onExternal` — обычно это одна строка
 * `url => new MessageUrlClickConfirm({ url })`. Если колбэк не передан,
 * переход всё равно отменяется: молча уйти со страницы по внешней ссылке
 * хуже, чем не показать диалог.
 * ***************************************************************************
 */

/**
 * Опции навешивания обработчика клика по ссылке.
 */
export interface LinkAttachOptions {
    /** Адрес. По умолчанию берётся из атрибута `href`. */
    url?: string | undefined;
    /** Что делать с внешней ссылкой: вызывается с адресом, если он задан. */
    onExternal?: (url: string) => void;
}

/**
 * ***************************************************************************
 * Является ли ссылка внутренней для текущего приложения.
 * @param url - Адрес ссылки.
 * @returns true, если origin совпадает с origin приложения.
 ***************************************************************************
 */
export function isInternal(url: string): boolean {

    // Адрес может быть относительным — URL() разрешит его относительно
    // текущей страницы. Невалидный адрес разрешить не удастся — он внешний
    try {
        const parsed = new URL(url, window.location.href);
        return parsed.origin === window.location.origin;
    } catch {
        return false;
    }

}

/**
 * ***************************************************************************
 * Обработчик клика по ссылке: внутренние пропускаем, внешние спрашиваем.
 *
 * Вызывать нужно на самом элементе ссылки, а не на контейнере: после
 * перерисовки списка контейнер остаётся прежним, а элементы `<a>` создаются
 * заново — и слушатель на старом узле не срабатывает. Поэтому обработчик
 * навешивается в том же проходе, где создаются ссылки.
 *
 * @param link - Элемент ссылки.
 * @param options - Опции.
 * @param options.url - Адрес. По умолчанию берётся из атрибута `href`.
 * @param options.onExternal - Что делать с внешней ссылкой:
 *   вызывается с адресом, если он задан.
 * @returns void
 ***************************************************************************
 */
export function attach(link: Element | null | undefined, options: LinkAttachOptions = {}): void {

    // Без узла подписываться не на что
    if (!link) return;

    link.addEventListener("click", (event) => {

        // Ссылка внутри карточки/сообщения: клик по ней не должен открывать
        // сам список или переключать чат
        event.stopPropagation();

        // Адрес берём из атрибута, а не из href-свойства: свойство нормализует
        // URL и для относительных адресов вернёт уже абсолютный
        const url = options.url || link.getAttribute("href");

        if (!url) return;

        // Внутренняя ссылка — переход разрешён, ничего не спрашиваем
        if (isInternal(url)) return;

        // Внешняя — переход отменяем в любом случае
        event.preventDefault();

        if (typeof options.onExternal === "function") {
            options.onExternal(url);
        }

    });

}

/**
 * ***************************************************************************
 * Навесить обработчики на готовую коллекцию ссылок.
 * @param links - Коллекция элементов (NodeList, Array или null/undefined).
 * @param options - Опции (см. attach).
 * @returns void
 ***************************************************************************
 */
export function attachAll(links: Iterable<Element> & ArrayLike<Element> | null | undefined, options: LinkAttachOptions = {}): void {

    if (!links || links.length === 0) return;

    for (const link of links) {
        attach(link, options);
    }

}
