/**
 * ***************************************************************************
 * Наблюдение за удалением элемента из DOM.
 *
 * Подписывается на изменения документа и вызывает колбэк один раз, когда
 * элемент перестаёт быть потомком `document.body`. Используется там, где
 * нужно попрощаться с ресурсом (аудио, видеопоток) в момент, когда узел
 * вычищает внешний код, а не мы сами.
 * ***************************************************************************
 */

/**
 * ***************************************************************************
 * Наблюдать за удалением элемента из DOM.
 * @param element - Отслеживаемый узел (без родителя — наблюдать не за чем).
 * @param callback - Вызывается один раз при исчезновении элемента.
 * @returns Наблюдатель (для ручного отключения) или null, если элемент
 *   не найден или не имеет родителя.
 * ***************************************************************************
 */
export function watchForRemoval(element: Node | null, callback: (element: Node) => void): MutationObserver | null {

    if (!element || !element.parentNode) {
        console.error("Элемент не найден или не имеет родителя");
        return null;
    }

    const observer = new MutationObserver(() => {
        // Проверяем, существует ли еще элемент в DOM
        if (!document.body.contains(element)) {
            callback(element);
            observer.disconnect();
        }
    });

    // Наблюдаем за всем документом
    observer.observe(document.body, {
        childList: true,
        subtree: true
    });

    return observer;

}
