/**
 * ***************************************************************************
 * Debounce (откладывание) — вызывает функцию только после того, как поток
 * вызовов «успокоился» на `wait` миллисекунд.
 *
 * Где применяется в проекте:
 * - ввод текста в textarea сообщения (не дёргаем рендер на каждую букву);
 * - отправка статуса «печатает», который иначе съедал лимит запросов.
 *
 * Отличие от throttle: при частых вызовах debounce выполнит функцию ОДИН раз —
 * после паузы, throttle — с фиксированной частотой во время потока вызовов.
 *
 * Важное свойство: у обёртки есть `.cancel()` и `.flush()`. Без них таймер
 * переживал закрытие формы и вызывал колбэк уже удалённого элемента.
 * ***************************************************************************
 */

/**
 * Отложенная функция с управлением таймером.
 */
export interface DebouncedFunction<T extends unknown[]> {

    /** Вызов обёртки: сбрасывает таймер и запоминает аргументы. */
    (...args: T): void;

    /** Отменить отложенный вызов (форма закрыта / элемент удалён). */
    cancel(): void;

    /** Выполнить немедленно, если вызов уже отложен. */
    flush(): void;

}

/**
 * Один отложенный вызов: аргументы, контекст и таймер живут в одном объекте,
 * чтобы состояние не рассинхронизировалось.
 */
interface PendingCall<T extends unknown[]> {

    /** Аргументы отложенного вызова. */
    args: T;

    /** Контекст вызова (`this`), с которым выполнится функция. */
    thisArg: unknown;

    /** Таймер отложенного запуска. */
    timer: ReturnType<typeof setTimeout>;

}

/**
 * ***************************************************************************
 * Создать debounce-обёртку.
 * @param fn - Функция, которую нужно откладывать.
 * @param wait - Пауза в миллисекундах без вызовов (по умолчанию 300).
 * @returns Обёртка с cancel() и flush().
 * ***************************************************************************
 */
export function debounce<T extends unknown[]>(fn: (...args: T) => void, wait = 300): DebouncedFunction<T> {

    // Что делать — проверяем сразу, чтобы ошибка была на месте создания,
    // а не через 300мс внутри таймера
    if (typeof fn !== "function") {
        throw new TypeError("Debounce: передан не функция.");
    }

    // Текущий отложенный вызов (null — откладывать нечего)
    let pending: PendingCall<T> | null = null;

    /**
     * ***************************************************************************
     * Вызов обёртки: сбрасывает таймер и запоминает аргументы.
     * ***************************************************************************
     */
    function debounced(this: unknown, ...args: T): void {

        // Запоминаем контекст и аргументы последнего вызова — выполним с ними
        const argsToUse = args;
        const thisToUse = this;

        // Предыдущий таймер сбрасываем: пользователь печатает снова
        if (pending) clearTimeout(pending.timer);

        // Новый отложенный вызов: таймер работает с локальными значениями,
        // а объект pending — единственное состояние для cancel()/flush()
        pending = {
            args: argsToUse,
            thisArg: thisToUse,
            timer: setTimeout(() => {

                // Таймер сработал — отложенного вызова больше нет
                pending = null;

                fn.apply(thisToUse, argsToUse);

            }, wait)
        };

    }

    /**
     * ***************************************************************************
     * Отменить отложенный вызов (форма закрыта / элемент удалён).
     * ***************************************************************************
     */
    debounced.cancel = function (): void {

        if (pending) clearTimeout(pending.timer);
        pending = null;

    };

    /**
     * ***************************************************************************
     * Выполнить немедленно, если вызов уже отложен.
     * ***************************************************************************
     */
    debounced.flush = function (): void {

        // Отложенного вызова нет — запускать нечего
        if (!pending) return;

        clearTimeout(pending.timer);

        const { args, thisArg } = pending;
        pending = null;

        fn.apply(thisArg, args);

    };

    return debounced;

}
