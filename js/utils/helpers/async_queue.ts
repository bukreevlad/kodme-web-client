/**
 * ***************************************************************************
 * AsyncQueue - очередь для последовательного выполнения асинхронных задач.
 * ***************************************************************************
 */
export class AsyncQueue {

    /** Очередь задач: каждая обёртка сама разрешает/отклоняет промис enqueue. */
    private readonly queue: Array<() => Promise<void>> = [];

    /** Флаг того, что очередь сейчас выполняет задачи. */
    private isProcessing = false;

    /**
     * ***************************************************************************
     * Добавить задачу в очередь.
     * @param task - Асинхронная функция, например: async () => { ... }.
     * @returns Promise с результатом задачи (отклоняется при ошибке задачи).
     * ***************************************************************************
     */
    async enqueue<T>(task: () => Promise<T> | T): Promise<T> {
        return new Promise<T>((resolve, reject) => {

            // Оборачиваем задачу, чтобы управлять её выполнением
            const taskWrapper = async (): Promise<void> => {
                try {
                    const result = await task();
                    resolve(result);
                } catch (err) {
                    reject(err);
                }
            };

            // Кладём в список
            this.queue.push(taskWrapper);

            // Пытаемся запустить обработку
            this.process();

        });
    }

    /**
     * ***************************************************************************
     * Логика последовательного выполнения.
     *
     * Задача из очереди не бросает исключения наружу: она сама разрешает или
     * отклоняет промис, полученный в enqueue, поэтому здесь достаточно дождаться
     * её завершения.
     * ***************************************************************************
     */
    private async process(): Promise<void> {

        // Если уже что-то обрабатывается или очередь пуста — выходим
        if (this.isProcessing || this.queue.length === 0) {
            return;
        }

        // Ставим флаг "занято"
        this.isProcessing = true;

        // Пока в очереди есть задачи — выполняем их одну за другой
        while (this.queue.length > 0) {
            const currentTask = this.queue.shift();

            // Очередь проверена в начале метода — к этому моменту задача есть
            if (!currentTask) break;

            await currentTask();
        }

        // Когда задачи кончились, снимаем флаг
        this.isProcessing = false;

    }

}
