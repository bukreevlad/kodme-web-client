// Импортируем presets
import { form } from "./form.js";
import { modal } from "./modal.js";
import { popover } from "./popover.js";

// Импортируем типы
import type { OverlayPreset } from "../types.js";

/**
 * ***************************************************************************
 * Реестр типов оверлеев.
 * ***************************************************************************
 *
 * Ключ реестра — это значение опции `type`, по которому `Overlay` находит
 * пресет: `new Overlay(tpl, { type: "modal" })`.
 *
 * Типы, которые различаются только дефолтами, разметкой обёртки и правилом
 * «что делать, когда не помещается» (форма, диалог, поповер), живут здесь.
 *
 * Поповер — единственный тип, который умеет привязываться к элементу или к
 * точке на экране. Диалог и форма вставляются туда, куда сказали, и о
 * соседних элементах ничего не знают: поэтому опций `targetNode`,
 * `targetNodeDirection` и `margin` у них больше нет.
 */
export const PRESETS: Record<string, OverlayPreset> = {
    form,
    modal,
    popover
};
