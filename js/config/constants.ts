/**
 * Временное (черновое) сообщение: заглушка для оптимистичного рендера до
 * ответа сервера. Пустые/нулевые поля — значения по умолчанию, вызывающий
 * код их переопределяет через spread (`{ ...TEMP_MESSAGE, ... }`).
 */
export interface TempMessage {

    /** Id (uuid v7 создаётся на клиенте). */
    id: string;

    /** Id автора. */
    created_user_id: string;

    /** URL аватара автора. */
    avatar_host_url: string;

    /** Отображаемое имя автора. */
    display_name: string;

    /** Id канала/диалога. */
    channel_id: string;

    /** Тип канала. */
    channel_type: string;

    /** Текст сообщения. */
    text: string | null;

    /** Id сообщения, на которое отвечаем. */
    reply_to_message_id: string | null;

    /** Сообщение-ответ целиком (форма — из стора, до ответа сервера null). */
    reply_to_message: unknown;

    /** Время создания (ISO). */
    created_at: string;

    /** Время редактирования (ISO) или null. */
    edited_at: string | null;

    /** Закреплено ли. */
    pinned: boolean;

    /** Id документа стикера или null. */
    sticker_document_id: string | null;

    /** Id набора стикера или null. */
    sticker_pak_id: string | null;

    /** Токен на чтение файла стикера или null. */
    sticker: string | null;

    /** Кнопки бота или null. */
    buttons: unknown;

    /** Флаг «временное» — уходит в очередь и не хранится на сервере. */
    is_temporary: boolean;

    /** Ожидает ответа сервера. */
    is_pending: boolean;

    /** Ошибка отправки (показываем повтор). */
    is_error_sending: boolean;

    /** Удалено. */
    is_deleted: boolean;

    /** Id пересланного сообщения или null. */
    forwarded_message_id: string | null;

    /** Отправлено ботом. */
    is_bot: boolean;

    /** Количество комментариев. */
    count_comments: number;

    /** Реакции (заполняет сервер после отправки). */
    reactions: unknown[];

    /** Вложения: массив или объект-мап (локальная форма temp-сообщения). */
    attachments: AttachmentsRaw;

    /** Аватары комментариев. */
    avatars_comments: unknown[];

}

