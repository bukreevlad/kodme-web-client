/**
 * ***************************************************************************
 * Z-лестница слоёв интерфейса.
 *
 * Значения хранятся готовыми строками классов, а не числами: Tailwind
 * собирает классы, сканируя исходники буквально, и конструкция
 * `z-[${N}]` в CSS не попадёт — класс просто исчезнет из сборки.
 *
 * Лестница:
 *
 * | Константа             | Класс      | Что это                          |
 * |-----------------------|------------|----------------------------------|
 * | `OVERLAY_BELOW`       | `z-[-1]`   | затемнение внутри обёртки, под контентом |
 * | `FORM`                | `z-100`    | обёртка формы-экрана             |
 * | `MODAL`               | `z-[1010]` | обёртка диалога                  |
 * | `POPOVER`             | `z-[1110]` | обёртка меню, эмодзи, меню бота  |
 * | `TOAST`               | `z-[9999]` | всплывающие уведомления          |
 *
 * **Почему между 1010 и 1110 ничего нет.** Раньше `media-viewer` вешал
 * `z-[1020]` и `image-cropper` — `z-[1030]` на своём контенте. Эти значения
 * ничего не делали: контент лежит внутри обёртки `z-[1010]`, а та создаёт
 * свой stacking context, и внутри него любой z-index сравнивается только с
 * соседями по этой же обёртке. На результат «кто выше — просмотрщик или
 * кроппер» влиял только порядок элементов в DOM.
 *
 * Задание «поднять просмотрщик над диалогом» через такой z-index не
 * сработает. Чтобы поднять слой целиком, нужно менять класс на обёртке
 * (`CDM_Z_INDEX.MODAL`), и это осознанное решение, а не правка числа.
 * ***************************************************************************
 */
export const CDM_Z_INDEX = {

    /** Затемнение внутри обёртки — обязано быть под контентом своего слоя. */
    OVERLAY_BELOW: "z-[-1]",

    /** Обёртка формы-экрана — самый нижний слой. */
    FORM: "z-100",

    /** Обёртка диалога — выше любой формы. */
    MODAL: "z-[1010]",

    /** Обёртка поповера — выше диалога: меню открывается поверх окна. */
    POPOVER: "z-[1110]",

    /** Уведомления — `position: fixed`, поэтому выше вообще всего. */
    TOAST: "z-[9999]"

};

