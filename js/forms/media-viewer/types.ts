// Импортируем типы
import type { MediaOriginal, MediaRendition } from "../../types/media.js";
import type { Thumbnail } from "../../utils/helpers/get_thumbnail_size_query.js";

/**
 * ***************************************************************************
 * MediaItemMetadata - метаданные медиафайла, которые читает просмотрщик.
 *
 * Читаются три блока контракта метадаты: превью (рендер слотов), рендерации
 * (меню качества плеера) и оригинал (соотношение сторон). Превью типизированы
 * как `Thumbnail` — это форма, которую принимает подборщик размера.
 * ***************************************************************************
 */
export interface MediaItemMetadata {

    /** Превью по ширинам (у локального файла — с Blob и blob:-ссылкой). */
    thumbnails?: Thumbnail[];

    /** Рендерации качества (меню качества видеоплеера). */
    renditions?: MediaRendition[];

    /** Оригинальный файл: ширина/высота для соотношения сторон. */
    original?: MediaOriginal;

}

/**
 * ***************************************************************************
 * MediaItem - медиафайл, показываемый в просмотрщике.
 *
 * Поля — контракт вложения (id, MIME-тип, токен, метадата) плюс локальные
 * поля показа ещё не загруженного файла (`_file` / `_objectUrl`).
 * ***************************************************************************
 */
export interface MediaItem {

    /** Id медиафайла (строка UUID либо числовой id). */
    id: string | number;

    /** MIME-тип ("image/jpeg", "video/mp4"); без него слот рендерится картинкой. */
    mime_type?: string;

    /** Токен доступа к защищённому файлу. */
    token?: string;

    /** Метаданные (превью, рендерации, оригинал). */
    metadata?: MediaItemMetadata | null;

    /** Локальный файл (предпросмотр до загрузки на сервер). */
    _file?: File | Blob | null;

    /** blob:-ссылка локального файла. */
    _objectUrl?: string | null;

}

/**
 * ***************************************************************************
 * MediaViewerOptions - настройки просмотрщика (дефолты задаёт constructor).
 * ***************************************************************************
 */
export interface MediaViewerOptions {

    /** Индекс стартового медиафайла (по умолчанию 0). */
    startIndex?: number;

    /** Зацикливать перелистывание (по умолчанию true). */
    loop?: boolean;

    /** Закрывать ли просмотрщик по Esc (по умолчанию true). */
    closeOnEsc?: boolean;

    /** Закрывать ли просмотрщик по клику на фон (по умолчанию true). */
    closeOnOverlay?: boolean;

    /** Максимальное увеличение изображения (по умолчанию 3). */
    maxZoom?: number;

    /** Контейнер, куда встраивается модальный DOM. */
    insertInto?: HTMLElement | null;

}

/**
 * ***************************************************************************
 * MediaViewerData - данные конструктора просмотрщика.
 * ***************************************************************************
 */
export interface MediaViewerData {

    /** Список медиафайлов для просмотра. */
    media?: MediaItem[];

    /** Настройки просмотрщика. */
    options?: MediaViewerOptions;

}

/**
 * ***************************************************************************
 * MediaViewerElements - элементы формы, собираемые в `_onBeforeOpen`.
 * Все опциональны: до сборки DOM у формы нет ни одного элемента.
 * ***************************************************************************
 */
export interface MediaViewerElements {

    /** Корень шаблона. */
    wrap?: HTMLElement | null;

    /** Сцена (цель жестов). */
    stage?: HTMLElement | null;

    /** Трек со слотами перелистывания (prev / active / next). */
    track?: HTMLElement | null;

    /** Счётчик «текущий / всего». */
    counter?: HTMLElement | null;

    /** Индикатор загрузки слота. */
    loader?: HTMLElement | null;

    /** Кнопка «‹». */
    btnPrev?: HTMLElement | null;

    /** Кнопка «›». */
    btnNext?: HTMLElement | null;

    /** Кнопка закрытия. */
    btnClose?: HTMLElement | null;

    /** Канвас активного слайда (цель зума и панорамирования). */
    canvas?: HTMLElement | null;

}

/**
 * ***************************************************************************
 * MediaPlayDetail - detail глобального события старта медиа
 * ("[app][audio]::media-play"): тип источника и id запущенного видео
 * (у аудио id нет — только тип).
 * ***************************************************************************
 */
export interface MediaPlayDetail {

    /** Тип источника: "audio" либо "video". */
    type: string;

    /** Id запущенного видео (сверяется с текущим слайдом). */
    id?: string | number;

}
