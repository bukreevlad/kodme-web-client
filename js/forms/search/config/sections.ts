/**
 * ***************************************************************************
 * Описание категорий поиска: событие сокета, подпись вкладки, кнопка панели.
 * Единственный источник правды для формы: всё, что различается между
 * категориями, лежит здесь — общий код (шаблон вкладок, первая загрузка,
 * догрузка, подписка на стор, обработчик скролла, поиск, teardown) общий.
 *
 * Состояние пагинации, сторы, списки, панели и скроллбары категорий живут
 * на форме с ключом `SectionId` (см. `index.ts` → `Search.stores`,
 * `Search.pagination` и т.д.), поэтому строковые ключи вида `${id}...`
 * в конфиг не входят.
 *
 * Поле `id` обязано совпадать с ключом объекта: общий код (догрузка, подписки
 * на стор) берёт из него имя для события сокета и для логов — без `id`
 * догрузка молча уходила бы в никуда. Инвариант проверяется типом: `SECTIONS`
 * типизирован отображаемым типом `{ [K in SectionId]: SearchSection<K> }`,
 * поэтому запись `{ channels: { id: "groups", ... } }` не соберётся.
 *
 * Порядок `SECTION_IDS` совпадает с порядком вкладок в шаблоне `_template()`.
 *
 ***************************************************************************
 */

/**
 * ***************************************************************************
 * Идентификаторы категорий поиска. Порядок — порядок вкладок в шапке формы.
 ***************************************************************************
 */
export const SECTION_IDS = ["channels", "groups", "users", "bots"] as const;

/**
 * Категория поиска.
 */
export type SectionId = (typeof SECTION_IDS)[number];

/**
 * ***************************************************************************
 * Описание категории поиска.
 *
 * @property id - Имя категории, совпадает с ключом объекта SECTIONS.
 * @property event - Событие сокета вида "[search]: get <id>".
 * @property createBotKey - Ключ подписи кнопки в шапке панели в
 *               `I18n.tree.forms.search`. Задаётся только там, где кнопка
 *               нужна (вкладка ботов).
 ***************************************************************************
 */
export interface SearchSection<K extends SectionId = SectionId> {

    /** Имя категории — совпадает с ключом объекта SECTIONS. */
    id: K;

    /** Событие сокета вида "[search]: get <id>". */
    event: string;

    /** Иконка пустого состояния вкладки (имя Tabler): показывается, когда
     *  поиск по категории ничего не дал. */
    emptyIcon: string;

    /** Ключ подписи кнопки в шапке панели (только вкладка ботов). */
    createBotKey?: "create_bot";

}

/**
 * ***************************************************************************
 * Категории поиска по идентификаторам.
 *
 * Отображаемый тип фиксирует пару «ключ ↔ id»: каждая запись обязана лежать
 * под своим ключом, а набор ключов обязан совпадать с SECTION_IDS.
 ***************************************************************************
 */
export const SECTIONS: { [K in SectionId]: SearchSection<K> } = {

    channels: {
        id: "channels",
        event: "[search]: get channels",
        emptyIcon: "broadcast"
    },

    groups: {
        id: "groups",
        event: "[search]: get groups",
        emptyIcon: "users-group"
    },

    users: {
        id: "users",
        event: "[search]: get users",
        emptyIcon: "user-search"
    },

    bots: {
        id: "bots",
        event: "[search]: get bots",
        emptyIcon: "robot",

        // Кнопка в шапке панели: у вкладки ботов есть «Создать бота»,
        // у остальных вкладок её нет
        createBotKey: "create_bot"
    }

};
