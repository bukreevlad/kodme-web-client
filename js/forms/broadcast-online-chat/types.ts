// Импортируем типы
import type { StoreItem } from "../../utils/store.js";

/**
 * ***************************************************************************
 * OnlineChatMessage - сообщение онлайн-чата трансляции в хранилище формы.
 *
 * Поля — только те, что реально читает код формы (имя автора и текст строки).
 * Служебные ключи (__domElements__) живут здесь же, потому что их пишет
 * подписка стора на добавление записей.
 * ***************************************************************************
 */
export interface OnlineChatMessage extends StoreItem {

    /** Id сообщения (UUIDv7 сервера). */
    id: string;

    /** Id автора (из него считается цвет имени). */
    created_user_id: string;

    /** Отображаемое имя автора. */
    display_name: string;

    /** Текст сообщения. */
    text: string;

    /** Отображённые копии строки (одно сообщение может попасть в список дважды). */
    __domElements__?: HTMLElement[];

}

/**
 * ***************************************************************************
 * Сужение payload'а сокета до сообщения онлайн-чата.
 *
 * Данные приходят по событию "[message]: new" с типом unknown, поэтому
 * сверяемся guard'ом, а не приведением типов.
 * @param payload - Полезная нагрузка сокета.
 * @returns true, если это сообщение с id.
 * ***************************************************************************
 */
export function isOnlineChatMessage(payload: unknown): payload is OnlineChatMessage {
    return typeof payload === "object" &&
        payload !== null &&
        "id" in payload &&
        typeof payload.id === "string";
}
