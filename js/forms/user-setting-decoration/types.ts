/**
 * ***************************************************************************
 * Данные фона чатов: элемент списка фонов в хранилище формы. `__domElements__`
 * — накопленные DOM-копии элемента (для удаления при item::removed).
 * ***************************************************************************
 */
export interface ChatBackgroundData {

    /** Имя SVG-файла фона. */
    id: string;

    /** DOM-копии элемента (заполняется компонентом). */
    __domElements__?: HTMLElement[];

}

/**
 * ***************************************************************************
 * Данные пресета акцентного цвета.
 * ***************************************************************************
 */
export interface BrandColorData {

    /** Id пресета (в т.ч. "default"). */
    id: string;

    /** Значение цвета (hex) или пустая строка — «цвет темы». */
    color: string;

}
