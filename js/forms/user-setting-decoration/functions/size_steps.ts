/**
 * Шаги размера интерфейса — множители от базового шрифта 16px.
 *
 * Пять градаций: дефолт 0.875 (14px — компактная база интерфейса) стоит
 * ровно по центру списка, поэтому «Нормальный» не смещён влево. Значения
 * хранятся в сессии строками-коэффициентами (`--interface-size: Nrem`).
 */
export const INTERFACE_SIZE_STEPS = [0.75, 0.8125, 0.875, 0.9375, 1] as const;

/**
 * Шаги размера текста сообщений — множители от базового шрифта 16px.
 *
 * Дефолт 1 (16px) — по центру списка, как и у интерфейса.
 */
export const MESSAGE_SIZE_STEPS = [0.875, 0.9375, 1, 1.0625, 1.125] as const;

/**
 * ***************************************************************************
 * nearestSizeStep - ближайший шаг к сохранённому значению.
 *
 * Старые сессии хранили любой коэффициент из прежнего диапазона 13–19px
 * (например, 1.1875 = 19px), которого может не быть в списке шагов.
 * Такое значение не должно ломать форму: подсвечиваем ближайший вариант,
 * а в сессию оно уедет только после следующего выбора пользователя.
 * @param steps - Допустимые шаги (по возрастанию).
 * @param value - Сохранённый множитель.
 * @returns Ближайший шаг из списка.
 * ***************************************************************************
 */
export function nearestSizeStep(steps: readonly number[], value: number): number {

    // Инвариант: список шагов — константы модуля, пустым не бывает.
    // Защита на случай расширения: пустой список вернёт переданное значение
    if (steps.length === 0) return value;

    let best = steps[0] ?? value;
    let bestDelta = Math.abs(value - best);

    for (const step of steps) {
        const delta = Math.abs(value - step);
        if (delta < bestDelta) {
            best = step;
            bestDelta = delta;
        }
    }

    return best;

}
