// Импортируем типы
import type { BroadcastPlay } from "../index.js";

/**
 * ***************************************************************************
 * WIDE_HANDLER - переключение широкого режима сцены трансляции.
 *
 * Как и для состояния эфира, единственный источник — атрибут на корне формы
 * (`data-video-wide`): JS меняет только его, вид целиком решает CSS
 * (css/forms/broadcast-play.css, раздел 3). Кнопка лежит в контролах плеера
 * (см. functions/init_player.ts) и приходит сюда событием "wide-toggle".
 *
 * @param form - Экземпляр формы.
 * @param wide - Новое состояние широкого режима.
 * ***************************************************************************
 */
export function wideHandler(form: BroadcastPlay, wide: boolean): void {

    // Если формы уже нет (событие пришло после закрытия) — молча выходим
    if (!form?.tpl) return;

    // setAttribute обновляет атрибут и сбрасывает его в DOM только при
    // изменении, поэтому лишних перерисовок нет
    form.tpl.setAttribute("data-video-wide", String(wide));

}
