// Импортируем типы
import type { BroadcastPlay } from "../index.js";

/**
 * Задержка перед показом лоадера при буферизации.
 *
 * Событие `waiting` у живого потока стреляет почти на каждом зазоре
 * буфера (дрожание сети, смена сегмента HLS), и лоадер мигал бы
 * десятки раз за минуту. Порог в 1.2 секунды отсекает микро-паузы:
 * лоадер появляется только тогда, когда поток реально встал.
 */
const STALL_DELAY_MS = 1200;

/**
 * ***************************************************************************
 * LOADER_CONTROL - единое управление лоадером в шапке формы трансляции.
 *
 * Лоадер крутится только в двух случаях:
 *   - идёт запуск источника (Start*Player вызван, но видео ещё не
 *     заиграло) — включает loaderShow, выключает событие `playing`;
 *   - поток реально встал (буферизация дольше STALL_DELAY_MS) —
 *     включает loaderWaiting по событию `waiting`.
 *
 * Раньше лоадер висел прямо на событии `waiting`, и на живом потоке
 * крутился почти постоянно. Все вызовы идут через эти функции, чтобы
 * состояние лоадера и его отложенный таймер не расходились.
 * ***************************************************************************
 */

/**
 * ***************************************************************************
 * Показать лоадер сразу (запуск источника).
 *
 * Отложенный показ от буферизации при этом снимается: лоадер уже
 * включён вручную, второй таймер ему не нужен.
 * @param form - Экземпляр формы.
 * ***************************************************************************
 */
export function loaderShow(form: BroadcastPlay): void {

    // Снимаем отложенный показ (снимать нечего — проверка внутри)
    loaderDispose(form);

    form.loader?.classList.remove("hidden");

}

/**
 * ***************************************************************************
 * Скрыть лоадер (видео заиграло или запуск завершился ошибкой).
 * @param form - Экземпляр формы.
 * ***************************************************************************
 */
export function loaderHide(form: BroadcastPlay): void {

    // Снимаем отложенный показ: `playing` пришло раньше порога —
    // буферизация была микро-паузой, лоадер ей не нужен
    loaderDispose(form);

    form.loader?.classList.add("hidden");

}

/**
 * ***************************************************************************
 * Буферизация: показать лоадер, если пауза длится дольше порога.
 *
 * Первое `waiting` только планирует показ, повторные, пока таймер
 * жив, ничего не делают. Как только приходит `playing`, таймер
 * снимается (loaderHide) и лоадер не появляется вовсе.
 *
 * @param form - Экземпляр формы.
 * ***************************************************************************
 */
export function loaderWaiting(form: BroadcastPlay): void {

    // Уже запланирован показ — новый таймер не нужен
    if (form.loaderTiming !== null) return;

    // Лоадера нет (закрытая форма) — включать нечего
    if (!form.loader) return;

    form.loaderTiming = setTimeout(() => {

        // invariant: таймер срабатывает один раз, поле чистим сразу
        form.loaderTiming = null;
        form.loader?.classList.remove("hidden");

    }, STALL_DELAY_MS);

}

/**
 * ***************************************************************************
 * Снять отложенный показ лоадера (ошибка запуска, закрытие формы).
 *
 * Без снятия таймер жил бы до самого закрытия и мог включить лоадер
 * у уже остановленного плеера.
 * @param form - Экземпляр формы.
 * ***************************************************************************
 */
export function loaderDispose(form: BroadcastPlay): void {

    // Таймер может быть не запущен — снимать нечего
    if (form.loaderTiming === null) return;

    clearTimeout(form.loaderTiming);
    form.loaderTiming = null;

}
