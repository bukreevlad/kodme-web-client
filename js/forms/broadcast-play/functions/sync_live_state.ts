// Импортируем utils
import { Logger } from "../../../utils/logs/logger.js";

// Импортируем типы
import type { BroadcastPlay } from "../index.js";

/**
 * ***************************************************************************
 * SYNC_LIVE_STATE - переводит форму в состояние «эфир идёт» / «эфир не идёт».
 *
 * Единственный источник состояния — атрибут `data-live` на КОРНЕ формы.
 * JS не трогает ни классы бейджа, ни прозрачность плашки: он меняет один
 * атрибут, всё остальное решает CSS (css/forms/broadcast-play.css, раздел 7).
 * За счёт этого состояние не может разойтись с данными — нечему расходиться.
 *
 * Живость = cast.is_live AND form.isStreamLive, а не просто cast.is_live
 * ------------------------------------------------
 * `cast.is_live` приходит один раз из ответа `[broadcast]: open` и дальше
 * не обновляется: ответом на остановку эфира служит `[broadcast]: update`,
 * но только если сокет подписан на комнату `broadcast::<id>`. При этом
 * `[broadcast]: get stream info` отдаёт `null`, когда потока нет — значит,
 * наличие потока узнаём из него.
 *
 * @param form - Экземпляр формы.
 * @returns Новое состояние эфира (false при ошибке).
 * ***************************************************************************
 */
export function syncLiveState(form: BroadcastPlay): boolean {

    try {

        // Если формы уже нет (событие пришло после закрытия) — молча выходим
        if (!form?.tpl) return false;

        // Состояние считаем по двум независимым признакам
        const isLive = Boolean(form.cast?.is_live) && Boolean(form.isStreamLive);

        // Пишем в атрибут. setAttribute обновляет атрибут и сбрасывает его
        // в DOM только при изменении, поэтому лишних перерисовок нет
        form.tpl.setAttribute("data-live", String(isLive));

        return isLive;

    } catch (error) {

        // Ломать из-за этой функции нельзя: это только подпись состояния,
        // форма продолжит работать и без неё
        Logger.error(error);
        return false;

    }

}
