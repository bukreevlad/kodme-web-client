// Импортируем functions
import { setState } from "./set_state.js";
import { startTimer } from "./start_timer.js";
// Именованный импорт: stopNoAnswerTimer — не startNoAnswerTimer этого модуля,
// иначе сюда подставлялся бы запуск таймера и тот не останавливался
import { stopNoAnswerTimer } from "./no_answer_timer.js";

// Импортируем типы
import type { Call } from "../index.js";

/**
 * ***************************************************************************
 * Переводит звонок в состояние «идёт разговор».
 *
 * Срабатывает, как только в комнате появился хоть один собеседник:
 * для инициатора это момент ответа, для принявшего — момент подключения.
 * До этого момента форма показывает оверлей вызова, а таймер
 * длительности ещё не идёт — прозвон разговором не считается.
 * @param form - Экземпляр формы.
 * @returns {void}
 * ***************************************************************************
 */
export function activate(form: Call): void {

    try {

        // Уже активны — повторный вход ничего не меняет
        if (form?.callState === "active") return;

        // Прячем оверлей, показываем плашку «я»
        setState(form, "active");

        // Отсчёт «нет ответа» больше не нужен
        stopNoAnswerTimer(form);

        // Таймер длительности звонка
        startTimer(form);

    } catch {
        // Ошибку не поднимаем: вызывается из событий комнаты
    }

}
