// Импортируем utils
import { Main } from "../../../main/index.js";

// Импортируем типы
import { isChannelRecord } from "../../../main/types.js";
import type { GroupTopics } from "../../index.js";

/**
 * ***************************************************************************
 * Подписка на обновление канала-группы в глобальном сторе клиента.
 *
 * Глобальный стор живёт вне формы, поэтому функция возвращает отписку —
 * форма вызывает её при закрытии, чтобы не утекать.
 * @param form - Экземпляр формы.
 * @returns Функция отписки от глобального стора либо null, если стора нет.
 * ***************************************************************************
 */
export function subscribeChannelItemUpdated(form: GroupTopics): (() => void) | null {

    // Синглтон главной формы — источник подписки; без него подписываться не на что
    const store = Main.instance?.store;
    if (!store) return null;

    // Подписываемся на событие обновления канала. Шаблон события передаётся
    // в вызов напрямую — промежуточная const схлопнула бы шаблонный литерал
    // в string, не проходящий в тип события стора
    return store.on(`item::updated::${form.channel.id}`, (data) => {

        // Пейлоад типизирован как unknown: обновляем форму только если
        // пришла запись канала
        if (isChannelRecord(data)) form._update(data);

    });

}
