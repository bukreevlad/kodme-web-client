// Импортируем utils
import { Logger } from "../../../../utils/logs/logger.js";

// Импортируем functions
import { applyLayout } from "../../functions/apply_layout.js";
import { syncPins } from "../../functions/sync_pins.js";
import { savePinned } from "../../functions/pinned_storage.js";

// Импортируем типы
import type { MeetPlay } from "../../index.js";

/**
 * ***************************************************************************
 * pinParticipantHandler - Делает участника главным (закрепляет его плитку)
 *           или открепляет, если главным был он.
 *
 * Личный выбор, а не модерация: закреплённого крупно видно только того,
 * кто его выбрал (личное закрепление). Поэтому состояние лежит на форме
 * (`form.pinnedIdentity`) и никуда не отправляется — в отличие от
 * принудительного режима сетки, который пишется в `room.metadata`.
 *
 * Работает и для трансляций: закреплённый эфир крупно — обычное дело,
 * и в режиме презентации это единственный способ показать именно его,
 * а не того, кто сейчас делится экраном.
 *
 * Повторное нажатие на уже закреплённого снимает закрепление, а не
 * переключает на другого: иначе «вернуть как было» пришлось бы искать
 * через меню в третий раз.
 * @param form - Экземпляр формы.
 * @param identity - Identity участника в комнате LiveKit.
 * @returns {void}
 * ***************************************************************************
 */
export function pinParticipantHandler(form: MeetPlay, identity: string | null | undefined): void {

    try {

        if (!form || !identity) return;

        // ---------- ПЕРЕКЛЮЧЕНИЕ ----------
        form.pinnedIdentity = form.pinnedIdentity === identity ? null : identity;

        // Личный выбор переживает перезаход в конференцию, но не
        // закрытие вкладки — ровно как режим сетки
        savePinned(form.meetId, form.pinnedIdentity);

        Logger.debug(`📌 [meet-play]: Главный участник -> ${form.pinnedIdentity || "никто"}`);
        // ---------- ПЕРЕКЛЮЧЕНИЕ ----------

        // Раскладываем сетку заново. Плитки не пересоздаются, видео
        // не перезапускается — applyLayout только переносит элементы
        // между списком и полосой
        applyLayout(form);

        // ---------- ЗНАЧОК ----------
        // Значок обновляем по факту, а не по прежнему значению: главный
        // ровно один, но после снятия закрепления значок должен исчезнуть
        // именно с той плитки, на которой стоял
        syncPins(form);
        // ---------- ЗНАЧОК ----------

    } catch (error) {
        Logger.error("🚨 [meet-play]: Ошибка закрепления участника:", error);
    }

}
