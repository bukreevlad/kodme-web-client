// Импортируем functions
import { updateFooter } from "./update_footer.js";

// Импортируем типы
import type { MeetPlay } from "../index.js";
import type { Participant, RemoteParticipant } from "livekit-client";

/**
 * ***************************************************************************
 * Синхронизирует отображение участника с его актуальным состоянием
 * в комнате.
 *
 * Практически все события LiveKit про треки приводят к одному и тому же
 * последствию: плитку участника в хранилище нужно обновить. Собрано в
 * одной функции ещё и потому, что заодно обновляется футер — состоянием
 * микрофона/камеры/экрана управляет не только сам участник, но и сервер
 * (принудительные блокировки), а значит иконки футера должны следовать за
 * событиями комнаты, а не только за нажатиями кнопок.
 * @param form - Экземпляр формы.
 * @param participant - Участник LiveKit.
 * @returns void
 * ***************************************************************************
 */
export function updateParticipant(
    form: MeetPlay,
    participant?: Participant | RemoteParticipant | null
): void {

    // Участник мог выйти между событием и обработкой — пропускаем
    if (!participant) return;

    // ---------- TILE ----------
    // Плитка обновляется, только если участник на текущей странице:
    // update() эмитит событие и для отсутствующих элементов, поэтому
    // проверка нужна, иначе появляется подписка на несуществующий элемент
    if (form.store.get(participant.identity)) {
        form.store.update(participant.identity, { participant: participant });
    }
    // ---------- TILE ----------

    // ---------- FOOTER ----------
    // Футер описывает только локального участника. Чужие треки на
    // кнопки не влияют, поэтому лишний рендер на каждое событие комнаты
    // (а их при 30 участниках сотни в минуту) не нужен
    if (participant.isLocal) updateFooter(form);
    // ---------- FOOTER ----------

}
