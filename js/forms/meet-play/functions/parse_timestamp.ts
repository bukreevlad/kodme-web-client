/**
 * ***************************************************************************
 * Границы, в пределах которых `meets.created_at` считается правдоподобным.
 *
 * Зачем границы
 * ------------
 * Точка отсчёта конференции приходит из базы (`timestamptz`), поэтому у неё
 * есть два класса проблем, и оба дают «часы не той эпохи»:
 *
 *   1. Разные форматы на разных путях данных: сервер отдаёт дату как ISO-строку
 *      через JSON, но в других ветках ответа это может оказаться UNIX-время
 *      (секунды или миллисекунды) числом или строкой.
 *   2. Рассинхронизация часов клиента и сервера/БД. Здесь направление известно
 *      заранее: клиент обычно спешит (часы впереди), поэтому дата из прошлого
 *      выглядит неправдоподобно далёкой.
 *
 * Конференция — событие, а не «вечная комната»: строка старше недели уже не
 * может описывать идущую встречу. Всё, что вне окна, трактуется как «данных
 * нет» — таймер тогда считает от подключения, что заведомо лучше, чем показать
 * пользователю 288:27:56.
 * ***************************************************************************
 */

/** Допустимый дрейф часов вперёд: 5 минут. */
export const MAX_FUTURE_DRIFT_MS = 5 * 60 * 1000;

/** Максимальный возраст точки отсчёта: 7 суток. */
export const MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000;

/**
 * Порог, разделяющий UNIX-время в секундах и в миллисекундах.
 * 10^12 секунд — это year 33658, то есть заведомо не наша эпоха; 10^12 мс —
 * это 2001 год. Всё, что выше порога, считаем миллисекундами.
 */
const MS_THRESHOLD = 1_000_000_000_000;

/**
 * Ограничения правдоподобия точки отсчёта.
 */
export interface ParseTimestampOptions {

    /** Максимальный возраст точки отсчёта, мс. */
    maxAgeMs?: number;

    /** Допустимый уход в будущее, мс. */
    maxFutureMs?: number;

}

/**
 * ***************************************************************************
 * Преобразует произвольное значение даты/времени в отметку времени в мс.
 *
 * Поддерживаются все варианты, которыми `created_at` реально приходит:
 * объект `Date`, число (секунды или миллисекунды), числовая строка (те же
 * единицы) и ISO-строка с часовым поясом.
 * @param raw - Исходное значение.
 * @param options - Дополнительные ограничения.
 * @returns Отметка времени в мс или `NaN`, если значение непригодно.
 * ***************************************************************************
 */
export function parseTimestampMs(raw: unknown, options: ParseTimestampOptions = {}): number {

    const { maxAgeMs = MAX_AGE_MS, maxFutureMs = MAX_FUTURE_DRIFT_MS } = options;

    if (raw === null || raw === undefined || raw === "") return NaN;

    let ts = NaN;

    // ---------- Date ----------
    if (raw instanceof Date) {
        ts = raw.getTime();
    }

    // ---------- число ----------
    else if (typeof raw === "number") {
        if (!Number.isFinite(raw)) return NaN;
        ts = raw > MS_THRESHOLD ? raw : raw * 1000;
    }

    // ---------- строка ----------
    else if (typeof raw === "string") {

        const trimmed = raw.trim();
        if (trimmed === "") return NaN;

        // Числовая строка: сначала проверяем, что это действительно число.
        // Именно из-за отсутствия этой проверки `Date.parse("1759000000")`
        // возвращал NaN, а таймер молча уезжал в другую эпоху.
        if (/^-?\d+(?:\.\d+)?$/.test(trimmed)) {
            const num = Number(trimmed);
            ts = num > MS_THRESHOLD ? num : num * 1000;
        } else {
            ts = Date.parse(trimmed);
        }

    }

    // ---------- неподдерживаемый тип ----------
    else {
        return NaN;
    }

    // ---------- ПРАВДОПОДОБИЕ ----------
    if (!Number.isFinite(ts) || ts <= 0) return NaN;

    const now = Date.now();

    // Будущее время (часы клиента спешат) и слишком далёкое прошлое —
    // оба означают, что точку отсчёта использовать нельзя
    if (ts > now + maxFutureMs) return NaN;
    if (now - ts > maxAgeMs) return NaN;

    return ts;

}
