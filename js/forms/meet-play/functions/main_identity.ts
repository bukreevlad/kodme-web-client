import type { MeetPlay } from "../index.js";

/**
 * ***************************************************************************
 * Кто на этом экране считается главным (крупной плиткой).
 *
 * Два источника, и они не равны:
 *   - `forcedFocus` — ПРИНУДИТЕЛЬНЫЙ фокус организатора: правило комнаты
 *     из `room.metadata`, одинаковое у всех, и оно важнее всего остального,
 *     включая личное закрепление;
 *   - `pinnedIdentity` — личное закрепление участника из его меню
 *     «Сделать главным» (`sessionStorage`), касается только его экрана.
 *
 * Значок закрепления на плитке рисуется по этой же функции, иначе значок
 * и реально крупная плитка могли бы указывать на разных людей: у
 * организатора с включённым фокусом крупным был бы он, а значок стоял бы
 * на том, кого он когда-то закрепил лично.
 * @param form - Экземпляр формы.
 * @returns Identity главного участника или null.
 * ***************************************************************************
 */
export function mainIdentity(form?: MeetPlay): string | null {

    return form?.forcedFocus || form?.pinnedIdentity || null;

}
