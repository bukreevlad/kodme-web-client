// Импортируем components
import { renderPin } from "../components/functions/render_pin.js";

// Импортируем functions
import { mainIdentity } from "./main_identity.js";

// Импортируем типы
import type { MeetPlay } from "../index.js";

/**
 * ***************************************************************************
 * Расставляет значки закрепления по всем плиткам сетки.
 *
 * Синхронизирует по факту, а не по прежнему значению: главный участник
 * ровно один, но значок должен появиться и исчезнуть именно на нужной
 * плите, а их в сетке может быть несколько десятков. Перебор дешевле
 * и надёжнее, чем помнить, где значок был до этого.
 *
 * Вызывается отовсюду, где главный мог смениться: из меню участника
 * (личное закрепление) и из разбора metadata комнаты (принудительный
 * фокус организатора). Без второго вызова значок остался бы
 * на прежней плитке до пересоздания участника.
 * @param form - Экземпляр формы.
 * @returns void
 * ***************************************************************************
 */
export function syncPins(form: MeetPlay): void {

    // Главный считается один раз на вызов: правило и закрепление
    // не меняются, пока мы обходим плитки
    const main = mainIdentity(form);

    Array.from(form.list?.querySelectorAll<HTMLElement>(":scope .item") || [])
        .forEach(tile => renderPin(tile, tile.dataset.identity === main));

}
