// Импортируем типы
import type { MeetBlockFlag } from "../types.js";

/**
 * ***************************************************************************
 * Горячие клавиши конференции: список и условия, при которых их можно
 * перехватывать. Единственный источник правды для обоих.
 *
 * Живёт отдельно от `functions/keyboard_shortcuts.ts` намеренно. Тот
 * модуль тянет обработчики, а те — диалоги, и диалог настроек сетки
 * рисует подсказку из этого же списка: если бы данные остались там же,
 * получился бы цикл импортов. Здесь нет ни одного импорта от форм —
 * только данные и чистая проверка, поэтому модуль можно проверить тестом
 * без DOM-шимов и без графа зависимостей.
 *
 * Подсказку в интерфейсе рисует `meet-grid-settings` из `SHORTCUTS`,
 * чтобы она не разошлась с реально работающими клавишами.
 *
 * Сопоставление идёт по `event.code`, а не по `event.key`. Это осознанный
 * выбор: `event.key` зависит от раскладки, и на русской под буквой «V»
 * физически стоит «м». Подсказка печатает латинские буквы — значит и
 * срабатывание должно быть по физической клавише, одинаково на любой
 * раскладке.
 */

/**
 * Описание одной горячей клавиши конференции.
 */
export interface Shortcut {

    /** Значение `KeyboardEvent.code`. */
    code: string;

    /** Подпись клавиши в интерфейсе. */
    label: string;

    /** Ключ подписи в `dialogs.grid_settings.hotkeys_map`. */
    locale: string;

    /** Ключ блокировки организатора. У пункта меню блокировки не бывает. */
    flag: MeetBlockFlag | "";

}

/**
 * Список горячих клавиш конференции.
 */
export const SHORTCUTS: readonly Shortcut[] = [
    { code: "Space", label: "Space", locale: "space", flag: "audio" },
    { code: "KeyV", label: "V", locale: "video", flag: "video" },
    { code: "KeyS", label: "S", locale: "screen", flag: "screen" },
    { code: "KeyH", label: "H", locale: "hand", flag: "" },
    { code: "KeyM", label: "M", locale: "menu", flag: "" }
];

/**
 * Список полей, в которых клавиши не перехватываются.
 * Пока пользователь печатает, «S» — это буква, а не демонстрация экрана.
 */
export const EDITABLE_SELECTOR = "input, textarea, select, [contenteditable]:not([contenteditable=\"false\"]), [role=\"textbox\"]";

/**
 * Минимальный контекст формы, нужный проверке горячих клавиш.
 * Выделен, чтобы модуль не тянул за собой весь тип формы.
 */
export interface ShortcutFormContext {

    /** Корневой элемент формы (для проверки фокуса и перекрытия диалогом). */
    tpl?: HTMLElement | null;

}

/**
 * ***************************************************************************
 * Проверяет, можно ли сейчас реагировать на клавиши конференции.
 *
 * Пропускаем пять случаев:
 *   1) нажата клавиша с модификатором: Ctrl+S — это «сохранить страницу»
 *      в браузере, Cmd+M — свернуть окно в macOS, и перехватывать их
 *      значит сломать системные сочетания;
 *   2) пользователь печатает (input / textarea / contenteditable);
 *   3) идёт ввод методом IME — `key` в этот момент ещё «мусорный»,
 *      а без проверки «V» с русской раскладки отключала бы камеру
 *      посреди набора слова;
 *   4) фокус в другой форме (открыт чат, настройки конференции и т.п.):
 *      горячие клавиши чужой формы тут неуместны;
 *   5) поверх конференции открыт диалог или контекстное меню.
 *
 * Отсутствие фокуса (`document.body`) — не повод пропускать: после клика
 * по сетке фокуса действительно нет, и это самый частый случай.
 * @param event - Событие нажатия клавиши.
 * @param form - Экземпляр формы MeetPlay.
 * @returns Можно ли обрабатывать событие.
 * ***************************************************************************
 */
export function canHandleShortcut(event: KeyboardEvent, form: ShortcutFormContext): boolean {

    // ---------- МОДИФИКАТОРЫ ----------
    // Shift оставляем: с ним те же буквы нужны для заглавных, а
    // сочетаний Shift+буква в конференции не задействовано
    if (event.ctrlKey || event.metaKey || event.altKey) return false;
    // ---------- МОДИФИКАТОРЫ ----------

    // ---------- ПОЛЕ ВВОДА ----------
    if ((event.target as Element | null)?.closest?.(EDITABLE_SELECTOR)) return false;
    // ---------- ПОЛЕ ВВОДА ----------

    // ---------- IME ----------
    // keyCode 229 — «идёт composition» по устаревшей, но всё ещё
    // используемой браузерами договорённости
    if (event.isComposing || event.keyCode === 229) return false;
    // ---------- IME ----------

    // ---------- ЧУЖАЯ ФОРМА ----------
    const active = document.activeElement;
    const activeInsideForm = active && form?.tpl?.contains?.(active);
    const activeIsNothing = !active || active === document.body || active === document.documentElement;

    if (!activeInsideForm && !activeIsNothing) return false;
    // ---------- ЧУЖАЯ ФОРМА ----------

    // ---------- ПЕРЕКРЫТО СЛОЕМ ----------
    // Слои конференции — диалоги и вложенные формы настроек — вставляются
    // внутрь её корня, поэтому ищем по всей форме, а не только по прямым
    // потомкам. У каждого типа оверлея своя обёртка: `.cdm-modal-wrap` у
    // диалога, `.cdm-form-wrap` у формы. Без проверки формы Escape закрыл бы
    // конференцию целиком поверх открытых настроек
    if (form?.tpl?.querySelector?.(".cdm-modal-wrap, .cdm-form-wrap")) return false;

    // Контекстное меню живёт вне формы (insertInto по умолчанию —
    // document.body) и само обрабатывает Esc
    if (document.querySelector?.(".cdm-context-menu")) return false;
    // ---------- ПЕРЕКРЫТО СЛОЕМ ----------

    return true;

}
