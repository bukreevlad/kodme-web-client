/**
 * ***************************************************************************
 * Метаданные участника LiveKit: разбор и безопасное слияние.
 *
 * Это НЕ то же самое, что `room.metadata` (его разбирает
 * `parse_room_state.ts`): там организатор хранит блокировки и режим
 * сетки для всей комнаты, а здесь каждый участник пишет в свои
 * собственные метаданные. В комнате их читают все, поэтому и «поднятая
 * рука» разлетается без единого запроса на сервер — см. 7.1.
 *
 * Требования к разбору те же, что у состояния комнаты: мусор не должен
 * ронять форму, а неизвестные значения не должны превращаться в «истину».
 * ***************************************************************************
 */

/**
 * Ключ поднятой руки в метаданных участника.
 */
export const HAND_RAISED_KEY = "hand_raised";

/**
 * Разобранные метаданные участника: произвольный объект, но читаемый
 * код только через известные ключи.
 */
export type ParticipantMetadata = Record<string, unknown>;

/**
 * ***************************************************************************
 * Приводит метаданные участника к разобранному объекту.
 *
 * Пустая строка — обычное состояние: сервер кладёт в токен только
 * `identity` и `name`, поэтому до первого `setMetadata` участник
 * разговаривает вовсе без метаданных.
 * @param metadata - Строка `participant.metadata`.
 * @returns Объект метаданных либо пустой объект.
 * ***************************************************************************
 */
export function parseParticipantMetadata(metadata?: string | null): ParticipantMetadata {

    if (typeof metadata !== "string" || !metadata) return {};

    let raw: unknown = null;
    try { raw = JSON.parse(metadata); } catch (error) { raw = null; }

    // Массив и примитив — не объект метаданных. Возвращаем пустой объект,
    // чтобы вызывающий код не различал «пусто» и «сломано»
    if (!raw || typeof raw !== "object" || Array.isArray(raw)) return {};

    return raw as ParticipantMetadata;

}

/**
 * ***************************************************************************
 * Поднята ли рука у участника.
 *
 * Строгое сравнение с `true`: строка `"true"` и число `1` из чужого
 * клиента или будущей версии протокола не должны включать бейдж.
 * @param participant - Участник LiveKit (или его подмножество с metadata).
 * @returns Поднята ли рука.
 * ***************************************************************************
 */
export function isHandRaised(participant?: { metadata?: string | null }): boolean {

    const raw = parseParticipantMetadata(participant?.metadata);

    return raw[HAND_RAISED_KEY] === true;

}

/**
 * ***************************************************************************
 * Собирает новую строку метаданных с заданным состоянием руки.
 *
 * Ключевой момент: `setMetadata` в LiveKit ЗАМЕНЯЕТ метаданные целиком,
 * а не сливает их. Если бы мы писали просто `JSON.stringify({ hand_raised: true })`,
 * то поднятие руки затирало бы всё, что участник положил туда раньше, —
 * и обратное действие уже не восстановило бы прежнее состояние. Поэтому
 * читаем текущие метаданные, меняем один ключ и записываем целиком.
 * @param metadata - Текущая строка метаданных.
 * @param raised - Новое состояние руки.
 * @returns Готовая строка для `setMetadata`.
 * ***************************************************************************
 */
export function withHandRaised(metadata: string | null | undefined, raised: boolean): string {

    // Сломаные метаданные не восстанавливаем: продолжаем с чистого
    // объекта, иначе `setMetadata` упал бы на попытке распарсить мусор
    const current = parseParticipantMetadata(metadata);

    current[HAND_RAISED_KEY] = raised === true;

    return JSON.stringify(current);

}
