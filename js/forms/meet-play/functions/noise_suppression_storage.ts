// Импортируем utils
import { Logger } from "../../../utils/logs/logger.js";

/**
 * Ключ настройки шумоподавления в localStorage.
 */
const NOISE_KEY = "meet_play_noise_suppression";

/**
 * ***************************************************************************
 * Читает настройку шумоподавления.
 *
 * Хранилище - localStorage, а не sessionStorage (как у режима сетки и
 * закрепления): это личная настройка звука конкретного устройства. Она
 * должна переживать закрытие вкладки и меняться один раз на устройстве
 * пользователя, а не на каждую конференцию.
 * @returns Включено ли шумоподавление (по умолчанию false).
 * ***************************************************************************
 */
export function loadNoiseSuppression(): boolean {

    try {

        const value = localStorage.getItem(NOISE_KEY);

        // Любое чужое значение, кроме явной «1», - это выключено:
        // повреждённое хранилище не должно включать фичу по недоразумению
        return value === "1";

    } catch (error) {
        Logger.warn("[meet-play][noise]: Не удалось прочитать настройку шумоподавления:", error);
        return false;
    }

}

/**
 * ***************************************************************************
 * Сохраняет настройку шумоподавления.
 *
 * Значения - строки "1"/"0": формат, а не булев тип, как у ключей
 * настроек конференции в этом же хранилище. Ошибки записи (квота,
 * приватный режим) гасятся здесь: настройка не стоит того, чтобы
 * ронять переключение тумблера.
 * @param enabled - Новое состояние настройки.
 * @returns void
 * ***************************************************************************
 */
export function saveNoiseSuppression(enabled: boolean): void {

    try {
        localStorage.setItem(NOISE_KEY, enabled ? "1" : "0");
    } catch (error) {
        Logger.warn("[meet-play][noise]: Не удалось сохранить настройку шумоподавления:", error);
    }

}
