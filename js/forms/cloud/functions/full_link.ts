/**
 * ***************************************************************************
 * Сборка полного адреса ссылки общего доступа:
 * https://<domain>/cloud/<token> — такая ссылка парсится в сообщениях
 * и открывает облако с этим элементом.
 * @param link - Значение ссылки (токен).
 * @returns Полный URL ссылки.
 * ***************************************************************************
 */
export function fullLink(link?: string | null): string {

    // Если ссылка не передана — возвращаем пустую строку
    if (!link) return "";

    // Собираем полный адрес
    return `${window.location.protocol}//${window.location.hostname}/cloud/${link}`;

}
