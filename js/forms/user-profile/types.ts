// Импортируем типы
import type { AvatarImageDocument } from "../../components/avatars.js";

/**
 * ***************************************************************************
 * UserProfileRecord - профиль пользователя в форме (ответ "[user]: get info"
 * — meta пользователя с флагом отношения к запрашивающему).
 *
 * Поля — только те, что реально читает форма. Служебное поле is_contact
 * пишут обработчики контекстного меню (добавление/удаление контакта),
 * оно объявлено здесь, в месте использования.
 * ***************************************************************************
 */
export interface UserProfileRecord {

    /** Id пользователя. */
    id: string;

    /** Отображаемое имя. */
    display_name: string;

    /** Публичная ссылка профиля. */
    link?: string | null;

    /** Описание профиля. */
    bio?: string | null;

    /** Документ аватара. */
    avatar?: AvatarImageDocument | null;

    /** Содержится ли пользователь в контактах запрашивающего. */
    is_contact?: boolean;

}
