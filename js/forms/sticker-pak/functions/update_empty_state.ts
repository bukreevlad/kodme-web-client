// Импортируем типы
import type { StickerPak } from "../index.js";

/**
 * ***************************************************************************
 * Переключение пустого состояния сетки стикеров.
 *
 * Пустое состояние показывается после загрузки пака, когда в нём нет
 * стикеров; список при пустоте прячется. Переключение — только классом
 * `hidden` (по правилам Tailwind v4 display-утилиты не комбинируются).
 *
 * @param form - Экземпляр формы.
 * ***************************************************************************
 */
export function updateEmptyState(form: StickerPak): void {

    const isEmpty = form.stickers.length === 0;

    // Пустое состояние: показываем/прячем
    form.empty?.classList.toggle("hidden", !isEmpty);

    // Сетка стикеров: прячем при пустом паке
    form.list?.classList.toggle("hidden", isEmpty);

}
