// Импортируем типы
import type { AvatarImageDocument } from "../../components/avatars.js";

/**
 * ***************************************************************************
 * SessionUserFields - поля профиля пользователя внутри сессии, которые
 * читает кластер настроек (главная форма, email, link, выбор аватара).
 *
 * Поле `user` хранится как `unknown` (внешние данные на границе localStorage),
 * поэтому формы читают его этим сужением — см. invariant в местах чтения.
 * ***************************************************************************
 */
export interface SessionUserFields {

    /** Id пользователя. */
    id: string;

    /** Отображаемое имя (собирается на сервере из имени и фамилии). */
    display_name: string;

    /** Email пользователя. */
    email: string;

    /** Имя пользователя. */
    first_name: string;

    /** Фамилия пользователя. */
    last_name: string;

    /** Публичная ссылка профиля (пустая строка — ссылка не задана). */
    link: string;

    /** Описание профиля. */
    bio: string;

    /** Документ аватара (null — аватар не задан). */
    avatar: AvatarImageDocument | null;

    /**
     * Тип активных push-уведомлений (`web` | `hms` | `fcm`; отсутствует или
     * пусто — уведомления выключены). Читается формой настроек уведомлений.
     */
    is_pushes?: string;

}
