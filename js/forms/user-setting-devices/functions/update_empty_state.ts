// Импортируем типы
import type { UserSettingDevices } from "../index.js";

/**
 * ***************************************************************************
 * Переключение заглушки «Других активных сессий нет».
 *
 * Заглушка касается только списка остальных устройств: текущая сессия
 * живёт в отдельном блоке «Это устройство» и в form.list не попадает.
 *
 * Пустоту показываем только после первой загрузки: пока идёт первый
 * запрос, непонятно — «других сессий нет» или «ещё не загрузилось».
 *
 * @param form - Экземпляр формы.
 * ***************************************************************************
 */
export function updateEmptyState(form: UserSettingDevices): void {

    // Определяем пустоту: первая страница загружена и в списке
    // других устройств нет ни одного элемента
    const isEmpty = form.isFirstLoaded === true && form.list?.children.length === 0;

    // Переключаем заглушку (span без display-утилит — одной пары достаточно)
    form.devicesEmpty?.classList.toggle("hidden", !isEmpty);

}
